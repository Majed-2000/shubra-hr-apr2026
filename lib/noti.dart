/// One notification: title, ISO date, and message body.
///
/// شرح الحقول:
/// - [name]: عنوان الإشعار (مثلاً "تذكير حضور").
/// - [date]: تاريخ ووقت إرسال الإشعار بصيغة ISO.
/// - [msg]:  نص الإشعار التفصيلي الذي يُعرض للمستخدم.
class noti {
  String? name;
  String? date;
  String? msg;
}
